/** Canonical Zod schemas -> JSON Schema, TypeScript exports and Python model registry. */
import { z } from "zod";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import {
  configSchema,
  GENERATOR_VERSION,
  SAVE_VERSION,
} from "../contracts/schemas/config";
import {
  snapshotSchema,
  cameraSchema,
  positionSchema,
  worldEventSchema,
} from "../contracts/schemas/contracts";
import {
  contentPackageSchema,
  editPlanSchema,
  objectConstraintSchema,
  emptyContent,
} from "../contracts/schemas/content";
import * as recording from "../contracts/schemas/recording";
const schemas = {
  WorldEvent: worldEventSchema,
  WorldConfig: configSchema,
  WorldSnapshot: snapshotSchema,
  CameraState: cameraSchema,
  Position: positionSchema,
  ContentPackage: contentPackageSchema,
  EditPlan: editPlanSchema,
  BoundConstraint: objectConstraintSchema,
  ...recording,
};
const source = Object.fromEntries(
  Object.entries(schemas).map(([name, schema]) => [
    name,
    z.toJSONSchema(schema, { unrepresentable: "any", io: "input" }),
  ]),
);
const body = JSON.stringify(source, null, 2) + "\n";
const digest = createHash("sha256").update(body).digest("hex");
const python = `# Generated by scripts/protocol.ts. Do not edit.\nfrom .schema_runtime import build_models\n\nSCHEMA_SHA256 = '${digest}'\nSCHEMAS = __import__('json').loads(${JSON.stringify(body)})\nglobals().update(build_models(SCHEMAS))\n__all__ = list(SCHEMAS)\n`;
const lock = JSON.parse(await readFile("package-lock.json", "utf8"));
const physics = lock.packages["node_modules/@dimforge/rapier3d-compat"];
if (!physics?.version || !physics?.integrity)
  throw new Error(
    "The Rapier artifact must have a locked version and integrity",
  );
const physicsBuild = `${physics.version}:${physics.integrity}`;
const outputs: Record<string, string> = {
  "packages/adapters/src/rapier/build-info.ts":
    "// Generated from the locked Rapier artifact by scripts/protocol.ts.\nexport const PHYSICS_BUILD = " +
    JSON.stringify(physicsBuild) +
    ";\n",
  "contracts/schemas.json": body,
  "contracts/compatibility/versions.json":
    JSON.stringify(
      {
        protocol: 1,
        saveFormat: SAVE_VERSION,
        generator: GENERATOR_VERSION,
        contentOperators: emptyContent().engineVersion,
      },
      null,
      2,
    ) + "\n",
  "src/chrona/protocol/generated.py": python,
  "packages/protocol/src/recording.ts":
    '// Generated by scripts/protocol.ts.\nexport * from "../../../contracts/schemas/recording";\n',
};
for (const [path, text] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8").catch(() => "")) !== text)
      throw new Error(`Stale generated protocol: ${path}`);
  } else {
    await mkdir(path.slice(0, path.lastIndexOf("/")), { recursive: true });
    await writeFile(path, text);
  }
}
console.log(
  `Protocol ${digest.slice(0, 12)}: ${Object.keys(source).length} shared schemas verified`,
);
